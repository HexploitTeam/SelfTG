"""The bot's slash-command surface, as one table.

Telegram's own command menu, `/commands` and the in-bot command screen are three
views of the same list: if a command is not here it is not sent to Telegram, not
documented and not routed. The router in :mod:`Com.bot.client` maps each `key`
to a coroutine and refuses to start quietly when a name has no handler, so the
menu cannot drift from the implementation.

`python3 -m Com.bot.registry` prints the Markdown table that `BOT_COMMANDS.md`
contains; that file is generated, never hand-edited.
"""
import logging

from telethon.tl.functions.bots import SetBotCommandsRequest
from telethon.tl.types import BotCommand, BotCommandScopeDefault

log = logging.getLogger("selftg.bot.registry")

# name, description (≤256 chars), category, handler key
COMMANDS = (
    ("start", "Open the control panel", "Core", "home"),
    ("menu", "Open the control panel", "Core", "home"),
    ("status", "Health of both clients", "Core", "status"),
    ("diagnostics", "Scheduler, memory, boot ids, queue", "Core", "diagnostics"),
    ("commands", "Every bot command, with descriptions", "Core", "commands"),
    ("ping", "Round-trip latency of the bot client", "Core", "ping"),
    ("id", "Owner id, chat id and bot username", "Core", "id"),
    ("version", "Build and boot information", "Core", "version"),
    ("cancel", "Abort a multi-step flow", "Core", "cancel"),
)

CATEGORIES = ("Core",)


def names():
    return [name for name, _desc, _cat, _key in COMMANDS]


def keys():
    return [key for _name, _desc, _cat, key in COMMANDS]


def by_category():
    """{category: [(name, description)]} in declaration order."""
    grouped = {category: [] for category in CATEGORIES}
    for name, description, category, _key in COMMANDS:
        grouped.setdefault(category, []).append((name, description))
    return grouped


def render_html():
    """Body of the /commands reply and the in-bot command screen."""
    lines = ["⌨️ <b>Bot commands</b>", ""]
    for category, entries in by_category().items():
        lines.append(f"<b>{category}</b>")
        for name, description in entries:
            lines.append(f"/{name} — {description}")
        lines.append("")
    lines.append("Everything else is a button in /start.")
    return "\n".join(lines)


def render_markdown():
    """The generated documentation, one table row per command."""
    lines = [
        "<!-- Generated by `python3 -m Com.bot.registry`; do not edit by hand. -->",
        "",
        "| Command | Description | Category |",
        "| --- | --- | --- |",
    ]
    for name, description, category, _key in COMMANDS:
        lines.append(f"| `/{name}` | {description} | {category} |")
    lines.append("")
    return "\n".join(lines)


def as_bot_commands():
    return [BotCommand(command=name, description=description)
            for name, description, _category, _key in COMMANDS]


async def register(client):
    """Publish the table to Telegram's command menu; never fatal."""
    try:
        await client(SetBotCommandsRequest(
            scope=BotCommandScopeDefault(),
            lang_code="",
            commands=as_bot_commands(),
        ))
        log.info("bot registry: %d commands published to Telegram", len(COMMANDS))
        return True
    except Exception:  # noqa: BLE001 - the menu is a nicety, not a dependency
        log.warning("bot registry: could not publish the command menu", exc_info=True)
        return False


if __name__ == "__main__":
    print(render_markdown(), end="")
